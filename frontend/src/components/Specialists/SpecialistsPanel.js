// src/components/Specialists/SpecialistsPanel.js
//
// Browse/edit panel for the shared `specialties` library -- both the
// hand-curated personas and the ones auto-generated by detect-specialty
// when a case doesn't fit an existing one. Edits here are visible to every
// account, not just the editor's own, since `specialties` is a single
// global Firestore collection (no per-user scoping). See
// docs/persona-generation-plan.md at the repo root.

import React, { useEffect, useState } from 'react';
import { X, Stethoscope, Pencil, Save, ChevronLeft, Plus, Trash2, AlertTriangle } from 'lucide-react';
import { getSpecialties, updateSpecialty } from '../../firebase';

const cloneConfig = (config) => JSON.parse(JSON.stringify(config));

const SpecialtyCard = ({ specialty, onClick }) => (
  <button
    onClick={onClick}
    className="text-left bg-white border border-surface-200 rounded-lg p-4 hover:border-blue-400 hover:shadow-md transition-all"
  >
    <div className="flex items-center justify-between mb-1">
      <h3 className="text-sm font-semibold text-gray-800">{specialty.label}</h3>
      <Stethoscope size={16} className="text-blue-500 flex-shrink-0" />
    </div>
    <p className="text-xs text-gray-500 mb-2">{specialty.personaTitle}</p>
    <p className="text-xs text-gray-600 line-clamp-2">{specialty.description}</p>
    <div className="flex gap-1 mt-2">
      {specialty.generated && (
        <span className="text-[10px] px-1.5 py-0.5 rounded bg-purple-100 text-purple-700">Auto-generated</span>
      )}
      {specialty.reviewStatus === 'pending' && (
        <span className="text-[10px] px-1.5 py-0.5 rounded bg-amber-100 text-amber-700">Pending review</span>
      )}
    </div>
  </button>
);

const FieldRow = ({ field, index, isEditing, onChange, onRemove }) => (
  <div className="flex items-start gap-2 py-2 border-b border-surface-100 last:border-0">
    <div className="flex-1">
      {isEditing ? (
        <input
          className="w-full text-xs border rounded px-2 py-1 mb-1"
          value={field.label}
          onChange={(e) => onChange(index, { ...field, label: e.target.value })}
          placeholder="Label"
        />
      ) : (
        <div className="text-xs font-medium text-gray-700">{field.label}</div>
      )}
      {isEditing ? (
        <textarea
          className="w-full text-xs border rounded px-2 py-1"
          value={field.description}
          onChange={(e) => onChange(index, { ...field, description: e.target.value })}
          placeholder="Description"
          rows={2}
        />
      ) : (
        <div className="text-xs text-gray-500">{field.description}</div>
      )}
    </div>
    <div className="w-16 flex-shrink-0">
      {isEditing ? (
        <input
          type="number"
          className="w-full text-xs border rounded px-2 py-1"
          value={field.points}
          onChange={(e) => onChange(index, { ...field, points: Number(e.target.value) })}
        />
      ) : (
        <div className="text-xs text-gray-700 text-right">{field.points} pts</div>
      )}
    </div>
    {isEditing && (
      <button onClick={() => onRemove(index)} className="text-red-400 hover:text-red-600 mt-1">
        <Trash2 size={14} />
      </button>
    )}
  </div>
);

const NumberInput = ({ label, value, onChange, isEditing }) => (
  <div className="flex items-center justify-between py-1">
    <span className="text-xs text-gray-600">{label}</span>
    {isEditing ? (
      <input
        type="number"
        className="w-20 text-xs border rounded px-2 py-1 text-right"
        value={value}
        onChange={(e) => onChange(Number(e.target.value))}
      />
    ) : (
      <span className="text-xs font-medium text-gray-800">{value}</span>
    )}
  </div>
);

const TextInput = ({ label, value, onChange, isEditing, textarea }) => (
  <div className="py-1">
    <div className="text-xs text-gray-500 mb-0.5">{label}</div>
    {isEditing ? (
      textarea ? (
        <textarea
          className="w-full text-xs border rounded px-2 py-1"
          value={value || ''}
          onChange={(e) => onChange(e.target.value)}
          rows={2}
        />
      ) : (
        <input
          className="w-full text-xs border rounded px-2 py-1"
          value={value || ''}
          onChange={(e) => onChange(e.target.value)}
        />
      )
    ) : (
      <div className="text-sm text-gray-800">{value || <span className="text-gray-400">—</span>}</div>
    )}
  </div>
);

const SpecialtyDetail = ({ specialty, user, onBack, onSaved }) => {
  const [isEditing, setIsEditing] = useState(false);
  const [config, setConfig] = useState(cloneConfig(specialty));
  const [isSaving, setIsSaving] = useState(false);
  const [error, setError] = useState(null);

  const canEdit = !!user && !user.isAnonymous;
  const scoring = config.articleScoring || {};

  const updateScoring = (key, value) => {
    setConfig(prev => ({ ...prev, articleScoring: { ...prev.articleScoring, [key]: value } }));
  };

  const updateFieldRow = (index, newField) => {
    const fields = [...scoring.fields];
    fields[index] = newField;
    updateScoring('fields', fields);
  };

  const removeFieldRow = (index) => {
    updateScoring('fields', scoring.fields.filter((_, i) => i !== index));
  };

  const addFieldRow = () => {
    updateScoring('fields', [
      ...(scoring.fields || []),
      { key: `field_${Date.now()}`, label: 'New Factor', description: '', points: 10, optional: false },
    ]);
  };

  const handleSave = async () => {
    const fields = config.articleScoring?.fields || [];
    if (!config.label?.trim() || !config.personaTitle?.trim() || fields.length === 0) {
      setError('Label, persona title, and at least one scoring field are required.');
      return;
    }
    for (const f of fields) {
      if (!f.label?.trim() || !f.description?.trim()) {
        setError('Every scoring field needs a label and description.');
        return;
      }
    }

    setIsSaving(true);
    setError(null);
    try {
      await updateSpecialty(specialty.id, config, user?.uid);
      setIsEditing(false);
      onSaved(config);
    } catch (e) {
      setError('Failed to save changes. Please try again.');
    } finally {
      setIsSaving(false);
    }
  };

  return (
    <div>
      <div className="flex items-center justify-between mb-4">
        <button onClick={onBack} className="flex items-center text-sm text-gray-500 hover:text-gray-700">
          <ChevronLeft size={16} className="mr-1" /> Back to all specialists
        </button>
        {canEdit && (
          isEditing ? (
            <div className="flex gap-2">
              <button
                onClick={() => { setIsEditing(false); setConfig(cloneConfig(specialty)); setError(null); }}
                className="text-xs px-3 py-1.5 text-gray-600 hover:text-gray-800"
              >
                Cancel
              </button>
              <button
                onClick={handleSave}
                disabled={isSaving}
                className="flex items-center text-xs px-3 py-1.5 bg-blue-600 text-white rounded hover:bg-blue-700 disabled:opacity-50"
              >
                <Save size={14} className="mr-1" /> {isSaving ? 'Saving...' : 'Save'}
              </button>
            </div>
          ) : (
            <button
              onClick={() => setIsEditing(true)}
              className="flex items-center text-xs px-3 py-1.5 border border-blue-600 text-blue-600 rounded hover:bg-blue-50"
            >
              <Pencil size={14} className="mr-1" /> Edit
            </button>
          )
        )}
      </div>

      {error && (
        <div className="flex items-center text-xs text-red-600 bg-red-50 border border-red-200 rounded px-3 py-2 mb-3">
          <AlertTriangle size={14} className="mr-2 flex-shrink-0" /> {error}
        </div>
      )}

      {(config.generated || config.reviewStatus === 'pending') && (
        <div className="flex items-center text-xs text-amber-700 bg-amber-50 border border-amber-200 rounded px-3 py-2 mb-3">
          <AlertTriangle size={14} className="mr-2 flex-shrink-0" />
          This persona was auto-generated{config.reviewStatus === 'pending' ? ' and has not been reviewed yet' : ''}. Verify its scoring criteria before relying on it for real cases.
        </div>
      )}

      <div className="grid grid-cols-2 gap-4 mb-4">
        <TextInput label="Label" value={config.label} isEditing={isEditing} onChange={(v) => setConfig(p => ({ ...p, label: v }))} />
        <TextInput label="Persona Title" value={config.personaTitle} isEditing={isEditing} onChange={(v) => setConfig(p => ({ ...p, personaTitle: v }))} />
        <TextInput label="Board Name" value={config.boardName} isEditing={isEditing} onChange={(v) => setConfig(p => ({ ...p, boardName: v }))} />
        <TextInput label="Chat Context Label" value={config.chatContextLabel} isEditing={isEditing} onChange={(v) => setConfig(p => ({ ...p, chatContextLabel: v }))} />
      </div>
      <TextInput label="Description" value={config.description} isEditing={isEditing} textarea onChange={(v) => setConfig(p => ({ ...p, description: v }))} />
      <TextInput label="Final Analysis Persona Role" value={config.finalAnalysis?.personaRole} isEditing={isEditing}
        onChange={(v) => setConfig(p => ({ ...p, finalAnalysis: { ...p.finalAnalysis, personaRole: v } }))} />

      <h4 className="text-xs font-semibold text-gray-700 uppercase tracking-wide mt-5 mb-2">Article Scoring</h4>
      <TextInput label="Evaluation Goal" value={scoring.evaluationGoal} isEditing={isEditing} textarea onChange={(v) => updateScoring('evaluationGoal', v)} />
      <div className="grid grid-cols-2 gap-x-4">
        <NumberInput label="Per Matched Event Points" value={scoring.perMatchedEventPoints} isEditing={isEditing} onChange={(v) => updateScoring('perMatchedEventPoints', v)} />
        <NumberInput label="Journal Impact Multiplier" value={scoring.journalImpactMultiplier} isEditing={isEditing} onChange={(v) => updateScoring('journalImpactMultiplier', v)} />
        <NumberInput label="Journal Impact Cap" value={scoring.journalImpactCap} isEditing={isEditing} onChange={(v) => updateScoring('journalImpactCap', v)} />
        <NumberInput label="Recency Decay Rate" value={scoring.yearDecayRate} isEditing={isEditing} onChange={(v) => updateScoring('yearDecayRate', v)} />
        <NumberInput label="Clinical Trial Bonus" value={scoring.clinicalTrialBonus} isEditing={isEditing} onChange={(v) => updateScoring('clinicalTrialBonus', v)} />
        <NumberInput label="Review Penalty" value={scoring.reviewPenalty} isEditing={isEditing} onChange={(v) => updateScoring('reviewPenalty', v)} />
        <NumberInput label="Citation Impact Multiplier" value={scoring.citationImpactMultiplier} isEditing={isEditing} onChange={(v) => updateScoring('citationImpactMultiplier', v)} />
        <NumberInput label="Citation Impact Cap" value={scoring.citationImpactCap} isEditing={isEditing} onChange={(v) => updateScoring('citationImpactCap', v)} />
      </div>

      <h4 className="text-xs font-semibold text-gray-700 uppercase tracking-wide mt-5 mb-2">Scoring Factors</h4>
      <div className="border border-surface-200 rounded-lg px-3">
        {(scoring.fields || []).map((f, i) => (
          <FieldRow key={f.key} field={f} index={i} isEditing={isEditing} onChange={updateFieldRow} onRemove={removeFieldRow} />
        ))}
      </div>
      {isEditing && (
        <button onClick={addFieldRow} className="flex items-center text-xs text-blue-600 hover:text-blue-800 mt-2">
          <Plus size={14} className="mr-1" /> Add scoring factor
        </button>
      )}

      <details className="mt-5">
        <summary className="text-xs font-semibold text-gray-700 uppercase tracking-wide cursor-pointer">
          Advanced: disease/event extraction config (raw JSON)
        </summary>
        {isEditing ? (
          <textarea
            className="w-full text-xs font-mono border rounded px-2 py-2 mt-2 h-48"
            value={JSON.stringify({ diseaseExtraction: config.diseaseExtraction, eventExtraction: config.eventExtraction }, null, 2)}
            onChange={(e) => {
              try {
                const parsed = JSON.parse(e.target.value);
                setConfig(p => ({ ...p, diseaseExtraction: parsed.diseaseExtraction, eventExtraction: parsed.eventExtraction }));
                setError(null);
              } catch {
                // Leave config unchanged until the JSON is valid again -- avoid
                // spamming an error on every keystroke while mid-edit.
              }
            }}
          />
        ) : (
          <pre className="text-[10px] font-mono bg-surface-50 rounded p-2 mt-2 overflow-auto max-h-48">
            {JSON.stringify({ diseaseExtraction: config.diseaseExtraction, eventExtraction: config.eventExtraction }, null, 2)}
          </pre>
        )}
      </details>
    </div>
  );
};

const SpecialistsPanel = ({ isOpen, onClose, user }) => {
  const [specialties, setSpecialties] = useState([]);
  const [isLoading, setIsLoading] = useState(false);
  const [selected, setSelected] = useState(null);
  const [loadError, setLoadError] = useState(null);

  useEffect(() => {
    if (!isOpen) return;
    setIsLoading(true);
    setLoadError(null);
    getSpecialties()
      .then((list) => setSpecialties(list.sort((a, b) => a.label.localeCompare(b.label))))
      .catch(() => setLoadError('Failed to load specialists. Please try again.'))
      .finally(() => setIsLoading(false));
  }, [isOpen]);

  if (!isOpen) return null;

  const handleSaved = (updatedConfig) => {
    setSpecialties(prev => prev.map(s => (s.id === updatedConfig.id ? updatedConfig : s)));
    setSelected(updatedConfig);
  };

  return (
    <div className="fixed inset-0 bg-black/40 z-[100] flex items-center justify-center p-6">
      <div className="bg-white rounded-xl shadow-xl w-full max-w-3xl max-h-[85vh] overflow-y-auto">
        <div className="flex items-center justify-between px-5 py-4 border-b border-surface-100 sticky top-0 bg-white">
          <h2 className="text-sm font-semibold text-gray-800 flex items-center">
            <Stethoscope size={18} className="mr-2 text-blue-600" /> Specialists
          </h2>
          <button onClick={onClose} className="text-gray-400 hover:text-gray-600">
            <X size={20} />
          </button>
        </div>

        <div className="p-5">
          {isLoading ? (
            <div className="text-sm text-gray-500">Loading specialists...</div>
          ) : loadError ? (
            <div className="text-sm text-red-600">{loadError}</div>
          ) : selected ? (
            <SpecialtyDetail
              specialty={selected}
              user={user}
              onBack={() => setSelected(null)}
              onSaved={handleSaved}
            />
          ) : (
            <>
              <p className="text-xs text-gray-500 mb-4">
                Every specialist here is automatically selected by the backend when a doctor submits a case -- there's no manual picker. When a case doesn't fit any of these well, a new one is generated automatically and added to this list for everyone.
              </p>
              <div className="grid grid-cols-2 gap-3">
                {specialties.map((s) => (
                  <SpecialtyCard key={s.id} specialty={s} onClick={() => setSelected(s)} />
                ))}
              </div>
            </>
          )}
        </div>
      </div>
    </div>
  );
};

export default SpecialistsPanel;
